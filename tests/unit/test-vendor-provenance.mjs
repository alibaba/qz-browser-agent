import assert from "node:assert/strict";
import { mkdtemp, rm, writeFile, mkdir, readFile, symlink } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";
import { runInNewContext } from "node:vm";
import { build } from "esbuild";
import { checkDependencyAssets, copyRuntimeAssets, createDependencyGraph, recordDependencyBuild, refreshDependencyProvenance, writeDependencyProvenance } from "../../scripts/vendor/assets.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const directory = await mkdtemp(join(tmpdir(), "qingzhou-dependency-audit-"));
const output = join(directory, "extension");
const lockPath = join(directory, "package-lock.json");
const packagePath = join(directory, "package.json");
const options = { extensionDir: output, lockPath, packagePath };
try {
  const graph = createDependencyGraph();
  await copyRuntimeAssets(output, graph);
  let symbolReads = 0;
  const sdkScope = { URL, TransformStream, get Symbol() { symbolReads++; return Symbol; } };
  const sdkSource = await readFile(join(output, "vendor/mcp-sdk.mjs"), "utf8");
  const getMcpSdk = runInNewContext(`${sdkSource.replace("export function getMcpSdk", "function getMcpSdk")}\ngetMcpSdk`, sdkScope);
  assert.equal(symbolReads, 0, "importing the factory leaves SDK schemas uninitialized");
  const sdk = getMcpSdk();
  assert.ok(symbolReads > 0, "the first connection initializes SDK schemas");
  const initializedReads = symbolReads;
  assert.equal(getMcpSdk(), sdk);
  assert.equal(symbolReads, initializedReads, "later connections reuse the initialized SDK");
  assert.equal(typeof sdk.Client, "function");
  assert.equal(typeof sdk.StreamableHTTPClientTransport, "function");
  assert.equal(typeof sdk.CfWorkerJsonSchemaValidator, "function");
  const bundled = await build({
    absWorkingDir: root, stdin: { contents: 'export { Client } from "@modelcontextprotocol/sdk/client/index.js"; export { StreamableHTTPClientTransport } from "@modelcontextprotocol/sdk/client/streamableHttp.js"; export { Readability } from "@mozilla/readability"; export { CfWorkerJsonSchemaValidator } from "@modelcontextprotocol/sdk/validation/cfworker";', resolveDir: root },
    outfile: join(output, "deps/runtime.js"), bundle: true, write: false, metafile: true, platform: "browser", format: "esm", logLevel: "silent",
  });
  await mkdir(join(output, "deps"), { recursive: true });
  await writeFile(join(output, "deps/runtime.js"), bundled.outputFiles[0].contents);
  recordDependencyBuild(graph, bundled.metafile, root, output);
  await writeDependencyProvenance(output, graph, {});
  await writeFile(lockPath, await readFile(join(root, "package-lock.json")));
  await writeFile(packagePath, await readFile(join(root, "package.json")));
  const manifest = await checkDependencyAssets(options);
  assert.equal(manifest.components["@modelcontextprotocol/sdk"].version, "1.31.0");
  assert.equal(manifest.components["@mozilla/readability"].version, "0.6.0");
  assert.equal(manifest.components.zod.version, "4.4.3");
  const cfworker = manifest.components["@cfworker/json-schema"];
  assert.equal(cfworker.version, "4.1.1");
  assert.match(cfworker.licenseSource, /5409fdc2bd144f68e8b28c61c71fcb16600000a6/);
  assert.deepEqual(await readFile(join(output, cfworker.licenseFiles[0])), await readFile(join(root, "scripts/vendor/licenses/cfworker.LICENSE.md")));
  assert.equal(manifest.components["zod-to-json-schema"].license, "ISC");
  assert.ok(manifest.assets["deps/runtime.js"].components.includes("zod-to-json-schema"));
  assert.ok(manifest.assets["deps/runtime.js"].components.some(key => key.endsWith("eventsource-parser")));
  const pdf = await readFile(join(output, "vendor/pdf.mjs"), "utf8");
  assert.match(pdf, /Local PDF worker is not registered/);
  assert.doesNotMatch(pdf, /new Function|LT \+ SCRIPT|createCDNWrapper/);
  assert.equal(manifest.staticEngines.mathjax.source, "mathjax-full/ts");
  assert.equal(manifest.components["mathjax-full"].version, "3.2.2");
  assert.doesNotMatch(sdkSource, /new Function|ajv\/dist/);
  await assert.rejects(async () => recordDependencyBuild(createDependencyGraph(), {
    inputs: { "node_modules/xlsx/dist/xlsx.mini.min.js": {} }, outputs: {},
  }, root, output), /minified dependency input/);
  const manifestPath = join(output, "vendor/provenance.json");
  const writeManifest = value => writeFile(manifestPath, JSON.stringify(value));
  const code = await readFile(join(output, "deps/runtime.js"));
  await writeFile(join(output, "deps/runtime.js"), "changed");
  await assert.rejects(checkDependencyAssets(options), /asset changed/);
  await refreshDependencyProvenance({ ...options, transform: "fixture-compiler@1" });
  assert.deepEqual((await checkDependencyAssets(options)).transforms, ["fixture-compiler@1"]);
  await writeFile(join(output, "deps/runtime.js"), code);
  await writeManifest(manifest);
  const licensePath = manifest.components["@mozilla/readability"].licenseFiles[0];
  const license = await readFile(join(output, licensePath));
  await rm(join(output, licensePath));
  await assert.rejects(checkDependencyAssets(options), /ENOENT/);
  await writeFile(join(output, licensePath), "modified notice");
  await assert.rejects(refreshDependencyProvenance(options), /asset changed/);
  await writeFile(join(output, licensePath), license);
  await writeManifest({ ...manifest, assets: { ...manifest.assets, "../outside.js": manifest.assets["deps/runtime.js"] } });
  await assert.rejects(checkDependencyAssets(options), /invalid dependency asset path/);
  await writeManifest({ ...manifest, components: { ...manifest.components, zod: { ...manifest.components.zod, licenseFiles: [] } } });
  await assert.rejects(checkDependencyAssets(options), /missing dependency license/);
  await writeManifest(manifest);
  await writeFile(join(output, "vendor/new.js"), "untracked runtime");
  await assert.rejects(checkDependencyAssets(options), /untracked dependency runtime/);
  await rm(join(output, "vendor/new.js"));
  await symlink(join(output, "deps"), join(output, "vendor/alias"));
  await assert.rejects(checkDependencyAssets(options), /symlink/);
  await rm(join(output, "vendor/alias"));
  await writeFile(lockPath, "changed lock");
  await assert.rejects(checkDependencyAssets(options), /dependency lock changed/);
  console.log(`dependency provenance tests passed (${Object.keys(manifest.assets).length} generated assets)`);
} finally { await rm(directory, { recursive: true, force: true }); }
